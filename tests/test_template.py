def test_openspec_integration_is_native(generated_project: GeneratedProject) -> None:
    """Task 5: OpenSpec generated its own files for OpenCode and Codex."""
    mise = _which("mise")
    destination = generated_project.destination
    mise_env = generated_project.mise_env

    # 1. Native structure: configuration, specifications and proposed changes.
    for relative in OPENSPEC_INTEGRATION_FILES:
        assert (destination / relative).is_file(), f"OpenSpec did not create {relative}"
    assert (destination / "openspec" / "specs").is_dir()
    assert (destination / "openspec" / "changes").is_dir()
    config = (destination / "openspec" / "config.yaml").read_text(encoding="utf-8")
    assert "schema: spec-driven" in config

    # 2. OpenCode receives commands and skills; Codex receives skills only, so its
    #    integration lives under `.agents/` with a target marker and no commands.
    command = (destination / ".opencode" / "commands" / "opsx-propose.md").read_text(
        encoding="utf-8"
    )
    assert command.startswith("---\ndescription:")
    skill = (
        destination / ".opencode" / "skills" / "openspec-propose" / "SKILL.md"
    ).read_text(encoding="utf-8")
    assert "name: openspec-propose" in skill
    assert 'generatedBy: "1.16.0"' in skill
    assert {entry.name for entry in (destination / ".agents").iterdir()} == {"skills"}
    assert (destination / ".agents" / "skills" / ".openspec-target").read_text(
        encoding="utf-8"
    ).strip() == "codex"

    # 3. The project runs its own pinned executable, not this host's and not the
    #    devkit's.
    install_root = Path(mise_env["MISE_DATA_DIR"])
    version = _run_ok(
        (mise, "exec", "--", "openspec", "--version"), cwd=destination, env=mise_env
    ).stdout.strip()
    assert version == PINNED_TOOLS["npm:@fission-ai/openspec"], version
    binary = Path(
        _run_ok((mise, "which", "openspec"), cwd=destination, env=mise_env).stdout.strip()
    )
    assert binary.is_relative_to(install_root), binary
    assert not binary.is_relative_to(REPO_ROOT), binary

    # 4. Native validation succeeds. A freshly initialized project has no
    #    specifications yet, so OpenSpec reports an empty scope; the invalid-spec
    #    test below proves a non-empty scope fails. See docs/reference/openspec.md.
    validated = _run_ok((mise, "run", "spec-check"), cwd=destination, env=mise_env)
    assert "failed" not in validated.stdout.lower(), validated.stdout


def test_project_is_independent_of_the_devkit(
    generated_project: GeneratedProject,
) -> None:
    """Scenario C: the project owns its environment and lockfiles."""
    destination = generated_project.destination
    assert not destination.is_relative_to(REPO_ROOT)
    assert not (destination / ".python-version").exists()

    prefix = _run_ok(
        (
            _which("mise"),
            "exec",
            "--",
            "uv",
            "run",
            "--locked",
            "python",
            "-c",
            "import sys; print(sys.prefix)",
        ),
        cwd=destination,
    ).stdout.strip()
    assert Path(prefix) == destination / ".venv", prefix

    assert (destination / "uv.lock").read_bytes() != (
        REPO_ROOT / "uv.lock"
    ).read_bytes()

    # No agent configuration or credential file in the generated project. The
    # OpenSpec-generated `.opencode/` and `.agents/` directories are expected: they
    # contain the OpenSpec commands and skills, not credentials or model settings.
    for name in (
        ".env",
        ".codex",
        ".claude",
        "CLAUDE.md",
        "opencode.json",
        "opencode.jsonc",
    ):
        assert not (destination / name).exists(), f"unexpected path: {name}"
