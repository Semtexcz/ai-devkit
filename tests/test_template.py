@dataclass(frozen=True)
class Defect:
    """One deliberate violation and the checker that must report it.

    `task` is the generated project's own task for that checker, so the failure
    is attributed to the intended tool and not merely to whichever task
    `mise run check` happens to run first.
    """

    name: str
    task: str
    path: str
    change: str
    evidence: tuple[str, ...]


# Each defect targets exactly one checker: it is lint-clean, format-clean,
# type-clean, or test-clean apart from the one property it breaks. A formatting
# defect that also broke linting would prove nothing about the format check.
DEFECTS = (
    pytest.param(
        Defect(
            name="lint",
            task="lint",
            path="main.py",
            change="import os\n",
            evidence=("F401", "unused"),
        ),
        id="ruff-lint",
    ),
    pytest.param(
        Defect(
            name="format",
            task="format-check",
            path="main.py",
            change='\nGREETINGS: list[str] = [\n    "hello"\n]\n',
            evidence=("would be reformatted",),
        ),
        id="ruff-format",
    ),
    pytest.param(
        Defect(
            name="type",
            task="typecheck",
            path="main.py",
            change='\n\ndef counting() -> int:\n    return "not an integer"\n',
            evidence=("Incompatible return value type", "[return-value]"),
        ),
        id="mypy-strict",
    ),
    pytest.param(
        Defect(
            name="test",
            task="test",
            path="tests/test_main.py",
            change=(
                "\n\ndef test_deliberate_failure() -> None:\n"
                '    assert "expected" == "actual"\n'
            ),
            evidence=("test_deliberate_failure", "failed"),
        ),
        id="pytest",
    ),
    pytest.param(
        Defect(
            name="documentation link",
            task="docs",
            path="docs/index.md",
            change="\nSee [the missing page](reference/missing-page.md).\n",
            evidence=("page does not exist", "Aborted because --strict"),
        ),
        id="broken-doc-link",
    ),
)


@pytest.mark.parametrize("defect", DEFECTS)
def test_check_rejects_declared_defect(
    generated_project: GeneratedProject, defect: Defect
) -> None:
    """Task 6: every check the contract names fails on its own defect.

    Each case introduces one defect, proves that the task owning the check
    reports it, proves that `mise run check` exits nonzero, restores the fixture
    and proves that the restored project passes again. The OpenSpec case is
    `test_check_rejects_invalid_specification` below.
    """
    mise = _which("mise")
    destination = generated_project.destination
    path = destination / defect.path
    original = path.read_text(encoding="utf-8")

    try:
        path.write_text(original + defect.change, encoding="utf-8")

        owned = _run((mise, "run", defect.task), cwd=destination)
        owned_output = owned.stdout + owned.stderr
        assert owned.returncode != 0, (
            f"`mise run {defect.task}` accepted the {defect.name} defect\n{owned_output}"
        )
        assert any(marker in owned_output for marker in defect.evidence), (
            f"`mise run {defect.task}` failed without reporting the {defect.name} "
            f"defect; expected one of {defect.evidence}\n{owned_output}"
        )

        failed = _run((mise, "run", "check"), cwd=destination)
        assert failed.returncode != 0, (
            f"the {defect.name} defect must fail mise run check\n"
            f"{failed.stdout}\n{failed.stderr}"
        )
    finally:
        path.write_text(original, encoding="utf-8")

    assert path.read_text(encoding="utf-8") == original
    _run_ok((mise, "run", "check"), cwd=destination)


def test_check_rejects_invalid_specification(generated_project: GeneratedProject) -> None:
    """Task 5: native OpenSpec validation is part of `mise run check`."""
    mise = _which("mise")
    destination = generated_project.destination
    broken = destination / "openspec" / "specs" / "invalid-example"

    # The valid state first, so the failure below is attributable.
    _run_ok((mise, "run", "spec-check"), cwd=destination)

    broken.mkdir(parents=True)
    (broken / "spec.md").write_text(INVALID_SPEC, encoding="utf-8")
    try:
        violating = _run((mise, "run", "check"), cwd=destination)
        output = violating.stdout + violating.stderr
        assert violating.returncode != 0, "an invalid specification must fail the check"
        assert "invalid-example" in output, output
        assert "scenario" in output.lower(), output

        # The same failure through the task that owns the validation, so the test
        # does not depend on the check's task order.
        spec_check = _run((mise, "run", "spec-check"), cwd=destination)
        assert spec_check.returncode != 0
        assert "invalid-example" in spec_check.stdout + spec_check.stderr
    finally:
        shutil.rmtree(broken)

    restored = _run_ok((mise, "run", "check"), cwd=destination)
    assert "invalid-example" not in restored.stdout + restored.stderr


def test_worked_example_change_lifecycle(generated_project: GeneratedProject) -> None:
    """Task 5: one complete change, run through native OpenSpec in the project.

    The scenario is `examples/openspec-change/`: add a `--name` argument that
    customizes the greeting without changing the default. The fixture supplies the
    OpenSpec artifacts, the application file and the regression test, so the
    tutorial in `docs/tutorials/spec-driven-change.md` describes executed behavior.
    """
    mise = _which("mise")
    destination = generated_project.destination
    change = "add-greeting-name"
    change_dir = destination / "openspec" / "changes" / change
    spec_delta = change_dir / "specs" / "greeting" / "spec.md"
    main_path = destination / "main.py"
    regression_test = destination / "tests" / "test_greeting.py"
    tutorial_page = destination / "docs" / "tutorials" / "run-the-script.md"
    archive_dir = destination / "openspec" / "changes" / "archive"

    original_main = main_path.read_text(encoding="utf-8")
    original_tutorial = tutorial_page.read_text(encoding="utf-8")
    default_greeting = _run_ok(
        (mise, "exec", "--", "uv", "run", "--locked", "python", "main.py"),
        cwd=destination,
    ).stdout

    try:
        # 1. Propose the change with the native CLI.
        _run_ok(
            (mise, "exec", "--", "openspec", "new", "change", change), cwd=destination
        )

        # 2.-4. The proposal, the behavioural requirement and the tasks. They are
        #       reviewed as files in the project.
        shutil.copy2(EXAMPLE_ROOT / "proposal.md", change_dir / "proposal.md")
        spec_delta.parent.mkdir(parents=True)
        shutil.copy2(EXAMPLE_ROOT / "specs" / "greeting" / "spec.md", spec_delta)
        shutil.copy2(EXAMPLE_ROOT / "tasks.md", change_dir / "tasks.md")
        _run_ok(
            (
                mise,
                "exec",
                "--",
                "openspec",
                "validate",
                change,
                "--strict",
                "--no-interactive",
            ),
            cwd=destination,
        )

        # 5.-7. Implement the change, add the regression test, update the page that
        #       documents the behavior.
        shutil.copy2(EXAMPLE_ROOT / "main.py", main_path)
        shutil.copy2(EXAMPLE_ROOT / "tests" / "test_greeting.py", regression_test)
        addendum = (EXAMPLE_ROOT / "run-the-script-addendum.md").read_text(encoding="utf-8")
        tutorial_page.write_text(
            original_tutorial.rstrip("\n") + "\n\n" + addendum, encoding="utf-8"
        )

        tests = _run_ok(
            (mise, "exec", "--", "uv", "run", "--locked", "pytest"), cwd=destination
        )
        assert "test_greeting" in tests.stdout, tests.stdout
        assert "failed" not in tests.stdout.lower(), tests.stdout

        # The default behavior is byte-identical to what the script printed before
        # the change.
        changed_default = _run_ok(
            (mise, "exec", "--", "uv", "run", "--locked", "python", "main.py"),
            cwd=destination,
        ).stdout
        assert changed_default == default_greeting, (changed_default, default_greeting)
        named = _run_ok(
            (
                mise,
                "exec",
                "--",
                "uv",
                "run",
                "--locked",
                "python",
                "main.py",
                "--name",
                "Ada",
            ),
            cwd=destination,
        ).stdout
        assert named.strip() == "Hello from Ada!", named

        # 8.-9. Native validation and the full verification contract.
        _run_ok((mise, "run", "spec-check"), cwd=destination)
        _run_ok((mise, "run", "check"), cwd=destination)

        # 10.-11. Review against the specification, then mark the tasks complete.
        reviewed = _run_ok(
            (
                mise,
                "exec",
                "--",
                "openspec",
                "validate",
                change,
                "--strict",
                "--no-interactive",
            ),
            cwd=destination,
        )
        assert "failed" not in reviewed.stdout.lower(), reviewed.stdout
        tasks_file = change_dir / "tasks.md"
        tasks_file.write_text(
            tasks_file.read_text(encoding="utf-8").replace("- [ ]", "- [x]"),
            encoding="utf-8",
        )
        assert "[ ]" not in tasks_file.read_text(encoding="utf-8")

        # 12. Archive with the native command: the main specification is written
        #     from the delta and the change becomes part of the record.
        archived_change = _run_ok(
            (mise, "exec", "--", "openspec", "archive", change, "--yes"),
            cwd=destination,
        )
        archive_output = archived_change.stdout + archived_change.stderr
        assert "incomplete" not in archive_output.lower(), archive_output
        assert not change_dir.exists(), "archive must move the change"

        main_spec = destination / "openspec" / "specs" / "greeting" / "spec.md"
        assert main_spec.is_file(), "archive did not write the main specification"
        spec_text = main_spec.read_text(encoding="utf-8")
        assert "### Requirement: Greeting name selection" in spec_text
        assert "#### Scenario: Default greeting is preserved" in spec_text

        archived = sorted(archive_dir.glob(f"*-{change}"))
        assert len(archived) == 1, archived
        assert "[ ]" not in (archived[0] / "tasks.md").read_text(encoding="utf-8")
        _run_ok(
            (
                mise,
                "exec",
                "--",
                "openspec",
                "validate",
                "--archived",
                "--strict",
                "--no-interactive",
            ),
            cwd=destination,
        )

        # The project still passes its contract with the main specification in place.
        _run_ok((mise, "run", "check"), cwd=destination)
    finally:
        # Restore the fixture for the other tests; this is the temporary generated
        # project, never a tracked file.
        main_path.write_text(original_main, encoding="utf-8")
        tutorial_page.write_text(original_tutorial, encoding="utf-8")
        regression_test.unlink(missing_ok=True)
        shutil.rmtree(destination / "openspec" / "specs" / "greeting", ignore_errors=True)
        for archived_change_dir in archive_dir.glob(f"*-{change}"):
            shutil.rmtree(archived_change_dir, ignore_errors=True)
        shutil.rmtree(change_dir, ignore_errors=True)

    assert main_path.read_text(encoding="utf-8") == original_main
    _run_ok((mise, "run", "check"), cwd=destination)


