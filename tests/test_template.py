"""End-to-end integration test for the first-project workflow.

Nothing is mocked. The test runs the pinned `mise`, `uv`, `git`, Copier and
OpenSpec executables and follows the documented recipes in
`docs/tutorials/first-python-project.md` and `docs/tutorials/spec-driven-change.md`:

1. native `uv init` creates an unpackaged application in a directory whose name
   contains spaces, outside this repository;
2. the Copier overlay is applied from a tagged template source;
3. the baseline development dependencies are installed with `uv add`;
4. the documented project-owned annotation is added to `main.py`;
5. the project's `uv.lock` is generated by native `uv lock`;
6. the project's `mise.lock` is generated by native `mise lock` and installed
   with `mise install --locked` in a throwaway mise installation;
7. the environment is rebuilt with that isolated toolchain, so the interpreter
   identity can be verified instead of assumed;
8. OpenSpec is initialized by the project's own pinned CLI;
9. the entry point, the smoke test and `mise run check` are executed;
10. the worked example in `examples/openspec-change/` runs the whole OpenSpec
    lifecycle — propose, validate, implement, test, archive — in the project;
11. file ownership, isolation and failure detection are asserted: each of the six
    named defects fails `mise run check` through the task that owns its checker.

Copier answers are rendered once more with quotes, backslashes, Unicode and
newlines, and the rendered `zensical.toml` is parsed back with `tomllib` to prove
that user input stays data instead of becoming TOML syntax.

The workflow reads no agent configuration and no credential store: it uses only
`mise`, `uv`, `git`, Copier, OpenSpec and the files it creates in a temporary
directory. OpenSpec runs with a throwaway `XDG_CONFIG_HOME`, so the user's global
OpenSpec configuration is never read for its state and never written.
"""

