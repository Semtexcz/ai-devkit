SCAFFOLD_ENTRY_POINT = "def main():\n"
ANNOTATED_ENTRY_POINT = "def main() -> None:\n"


@dataclass(frozen=True)
class GeneratedProject:
    """Evidence collected while creating and verifying the project."""

    destination: Path
    scaffold_main: str
    overlay_main: str
    scaffold_pyproject: str
    overlay_pyproject: str
    git_status_before: str
    mise_env: Mapping[str, str]


@pytest.fixture(scope="module")
def template_repo(tmp_path_factory: pytest.TempPathFactory) -> Path:
    """A temporary tagged git repository holding the devkit template source."""
    git = _which("git")

    repo = tmp_path_factory.mktemp("template source") / "ai-devkit template"
    repo.mkdir()
    shutil.copy2(REPO_ROOT / "copier.yml", repo / "copier.yml")
    shutil.copytree(
        REPO_ROOT / "templates",
        repo / "templates",
        ignore=shutil.ignore_patterns("__pycache__", "*.pyc"),
    )
    _run_ok((git, "init", "--quiet"), cwd=repo)
    # Acceptance-platform files are not executable; record that in the fixture so
    # rendered files inherit the same mode instead of this host's mount defaults.
    _run_ok((git, "config", "core.fileMode", "false"), cwd=repo)
    _run_ok((git, "add", "--all"), cwd=repo)
    _run_ok(
        (git, *GIT_IDENTITY, "commit", "--quiet", "-m", "overlay fixture"), cwd=repo
    )
    _run_ok((git, "tag", TEST_TAG), cwd=repo)
    return repo


def _isolated_mise_env(base: Path) -> dict[str, str]:
    """Point mise at a throwaway installation under the fixture.

    The generated project's `mise.lock` must be produced and installed without
    reusing anything that happens to be installed on this host and without
    writing towards the devkit's tracked files.

    `XDG_CONFIG_HOME` is redirected for the same reason: OpenSpec keeps its global
    configuration and telemetry state under `$XDG_CONFIG_HOME/openspec/`, and a
    test must not read or write the user's own copy. The project's own OpenSpec
    configuration lives in `openspec/config.yaml`, which this does not affect.
    """
    return {
        "MISE_DATA_DIR": str(base / "mise data"),
        "MISE_CACHE_DIR": str(base / "mise cache"),
        "MISE_STATE_DIR": str(base / "mise state"),
        "XDG_CONFIG_HOME": str(base / "config"),
    }


@pytest.fixture(scope="module")
def generated_project(
    tmp_path_factory: pytest.TempPathFactory, template_repo: Path
) -> GeneratedProject:
    """Create the project once with the real tools, then verify it per scenario."""
    mise = _which("mise")

    base = tmp_path_factory.mktemp("first-python-project")

    git_status_before = git_status()

    # 1. Native uv initialization. The destination contains a space and lives
    #    outside this repository.
    destination = base / "script project"
    _run_ok(
        (mise, "exec", "--", "uv", "init", *UV_INIT_FLAGS, str(destination)),
        cwd=REPO_ROOT,
    )
    scaffold_main = (destination / "main.py").read_text(encoding="utf-8")
    scaffold_pyproject = (destination / "pyproject.toml").read_text(encoding="utf-8")

    # 2. The Copier overlay, applied from the tagged template source.
    _run_ok(
        (
            mise,
            "exec",
            "--",
            "uv",
            "run",
            "--locked",
            "copier",
            "copy",
            "--vcs-ref",
            TEST_TAG,
            "--defaults",
            str(template_repo),
            str(destination),
        ),
        cwd=REPO_ROOT,
    )
    overlay_main = (destination / "main.py").read_text(encoding="utf-8")
    overlay_pyproject = (destination / "pyproject.toml").read_text(encoding="utf-8")

    # 3. Baseline development dependencies, installed by uv inside the project so
    #    that the project's own mise.toml selects the pinned Python and uv.
    _run_ok(
        (mise, "exec", "--", "uv", "add", "--dev", *DEV_DEPENDENCIES), cwd=destination
    )

    # 4. The documented project-owned edit. Copier never makes this edit.
    assert SCAFFOLD_ENTRY_POINT in overlay_main
    (destination / "main.py").write_text(
        overlay_main.replace(SCAFFOLD_ENTRY_POINT, ANNOTATED_ENTRY_POINT, 1),
        encoding="utf-8",
    )

    # 5. Native lockfile generation and verification, one per ownership layer.
    _run_ok((mise, "exec", "--", "uv", "lock"), cwd=destination)
    _run_ok((mise, "exec", "--", "uv", "lock", "--check"), cwd=destination)

    # 6. The project's own toolchain lock, produced and installed by native mise
    #    in a throwaway installation: `mise install --locked` must satisfy the
    #    generated mise.lock, not tools that happen to exist on this host.
    mise_env = _isolated_mise_env(base)
    _run_ok((mise, "trust"), cwd=destination, env=mise_env)
    _run_ok((mise, "lock"), cwd=destination, env=mise_env)
    _run_ok((mise, "install", "--locked"), cwd=destination, env=mise_env)

    # 7. Recreate the environment with that isolated toolchain. The first `.venv`
    #    was created by the host's mise, so reusing it would prove nothing about
    #    the interpreter the project's own lockfile installs. `uv venv --clear`
    #    rebuilds it from the interpreter this mise selects; `uv sync --locked`
    #    repopulates it from uv.lock.
    _run_ok((mise, "exec", "--", "uv", "venv", "--clear"), cwd=destination, env=mise_env)
    _run_ok((mise, "exec", "--", "uv", "sync", "--locked"), cwd=destination, env=mise_env)

    # 8. Native OpenSpec initialization inside the project, with the project's own
    #    pinned CLI. This is the documented command; the devkit's own openspec/
    #    directory is never copied into a project.
    _run_ok(
        (
            mise,
            "exec",
            "--",
            "openspec",
            "init",
            "--tools",
            ",".join(OPENSPEC_TOOLS),
            "--profile",
            "core",
        ),
        cwd=destination,
        env=mise_env,
    )

    # 9. The entry point, the smoke test and the project's own verification.
    _run_ok(
        (mise, "exec", "--", "uv", "run", "--locked", "python", "main.py"),
        cwd=destination,
    )
    smoke = _run_ok(
        (mise, "exec", "--", "uv", "run", "--locked", "pytest"), cwd=destination
    )
    assert "1 passed" in smoke.stdout, smoke.stdout
    _run_ok((mise, "run", "check"), cwd=destination)
    # The freshly locked and installed toolchain must run the checks too.
    _run_ok((mise, "run", "check"), cwd=destination, env=mise_env)

    return GeneratedProject(
        destination=destination,
        scaffold_main=scaffold_main,
        overlay_main=overlay_main,
        scaffold_pyproject=scaffold_pyproject,
        overlay_pyproject=overlay_pyproject,
        git_status_before=git_status_before,
        mise_env=mise_env,
    )


def test_generated_project_has_working_checks(
    generated_project: GeneratedProject,
) -> None:
    """Scenario A: the generated project runs, tests and verifies itself."""
    destination = generated_project.destination
    assert " " in destination.name, "the destination must exercise spaces in its path"

    for relative in OVERLAY_FILES:
        assert (destination / relative).is_file(), f"missing overlay file: {relative}"

    app = _run_ok(
        (_which("mise"), "exec", "--", "uv", "run", "--locked", "python", "main.py"),
        cwd=destination,
    )
    assert app.stdout.strip(), "the entry point produced no output"


def test_dependencies_are_exact_and_locked(generated_project: GeneratedProject) -> None:
    """Scenario A: the release's baseline versions are recorded by uv itself."""
    pyproject_path = generated_project.destination / "pyproject.toml"
    pyproject = tomllib.loads(pyproject_path.read_text(encoding="utf-8"))

    assert pyproject["project"]["name"] == "script-project"
    assert pyproject["project"]["dependencies"] == []
    assert set(pyproject["dependency-groups"]["dev"]) == set(DEV_DEPENDENCIES)
    # Unpackaged application: no build backend and no workspace membership.
    assert "build-system" not in pyproject
    assert "workspace" not in pyproject_path.read_text(encoding="utf-8")

    lockfile = (generated_project.destination / "uv.lock").read_text(encoding="utf-8")
    assert 'name = "script-project"' in lockfile
    for requirement in DEV_DEPENDENCIES:
        name, version = requirement.split("==")
        assert re.search(rf'name = "{name}"\nversion = "{version}"', lockfile), (
            f"uv.lock does not pin {name}=={version}"
        )


def test_overlay_owns_no_application_code_or_manifest(
    generated_project: GeneratedProject,
) -> None:
    """Scenario B: uv and the developer own main.py and pyproject.toml."""
    destination = generated_project.destination

    # Native scaffold shape, including the missing annotation that mypy rejects.
    assert generated_project.scaffold_main.startswith(SCAFFOLD_ENTRY_POINT)
    assert ANNOTATED_ENTRY_POINT not in generated_project.scaffold_main

    # Copier rendered neither file: both are byte-identical to the uv output.
    assert generated_project.overlay_main == generated_project.scaffold_main
    assert generated_project.overlay_pyproject == generated_project.scaffold_pyproject

    # The only change to main.py is the documented project-owned annotation.
    expected_main = generated_project.scaffold_main.replace(
        SCAFFOLD_ENTRY_POINT, ANNOTATED_ENTRY_POINT, 1
    )
    assert (destination / "main.py").read_text(encoding="utf-8") == expected_main

    # And no template file could ever render those paths.
    template_root = REPO_ROOT / "templates"
    for path in template_root.rglob("*"):
        assert path.name not in FORBIDDEN_TEMPLATE_FILES, f"overlay renders {path}"
        # OpenSpec and the harnesses own their generated integrations; the overlay
        # must not carry a second copy that would drift from the CLI's output.
        parts = set(path.relative_to(template_root).parts)
        assert not parts & AGENT_INTEGRATION_DIRECTORIES, f"overlay copies {path}"
    assert not (destination / ".python-version").exists()


def test_copier_provenance_is_recorded(
    generated_project: GeneratedProject, template_repo: Path
) -> None:
    """Scenario B: provenance comes from native Copier answers."""
    answers_path = generated_project.destination / ".copier-answers.yml"
    assert answers_path.is_file()

    answers = {}
    for line in answers_path.read_text(encoding="utf-8").splitlines():
        if not line or line.startswith("#"):
            continue
        key, _, value = line.partition(": ")
        answers[key] = value

    assert answers["_src_path"] == str(template_repo)
    assert answers["_commit"] == TEST_TAG
    assert answers["project_name"] == generated_project.destination.name


def test_project_toolchain_lockfile(generated_project: GeneratedProject) -> None:
    """Scenario A: native `mise lock` records the project's own toolchain."""
    destination = generated_project.destination

    # The rendered configuration is the only statement of the tool versions.
    rendered = tomllib.loads((destination / "mise.toml").read_text(encoding="utf-8"))
    assert rendered["tools"] == PINNED_TOOLS

    lock_path = destination / "mise.lock"
    assert lock_path.is_file(), "the generated project has no mise.lock"

    locked = tomllib.loads(lock_path.read_text(encoding="utf-8"))
    tools = locked["tools"]
    # Exactly the tools the rendered mise.toml declares, at the pinned versions.
    assert set(tools) == set(PINNED_TOOLS)
    for name, version in PINNED_TOOLS.items():
        entries = tools[name]
        assert [entry["version"] for entry in entries] == [version], name
        assert entries[0]["backend"] in {name, f"core:{name}"}, name
        if name.startswith("npm:"):
            # mise locks an npm tool through its npm dependency graph instead of a
            # per-platform archive: the sidecar records the graph, the entry
            # records its path and digest.
            sidecar = entries[0]["aube"]
            assert sidecar["digest"].startswith("sha256:"), name
            sidecar_path = destination / sidecar["path"]
            assert sidecar_path.is_dir(), sidecar_path
            assert any(sidecar_path.iterdir()), sidecar_path
        else:
            platform = entries[0]["platforms.linux-x64"]
            assert platform["checksum"].startswith("sha256:"), name
            assert platform["url"].startswith("https://"), name

    # Generated by mise in the project, not copied from this repository.
    assert lock_path.read_bytes() != (REPO_ROOT / "mise.lock").read_bytes()

    # `mise install --locked` installed into the throwaway fixture installation,
    # and the project resolves its interpreter from there.
    install_root = Path(generated_project.mise_env["MISE_DATA_DIR"])
    assert not install_root.is_relative_to(REPO_ROOT)
    interpreter = _run_ok(
        (_which("mise"), "which", "python"),
        cwd=destination,
        env=generated_project.mise_env,
    ).stdout.strip()
    assert Path(interpreter).is_relative_to(install_root), interpreter


def test_environment_uses_the_isolated_interpreter(
    generated_project: GeneratedProject,
) -> None:
    """Task 10B: the virtual environment was built by the project's own toolchain.

    Comparing version strings would pass even if `.venv` had been created by a
    different installation of the same interpreter, so this compares the base
    prefix and the resolved interpreter path instead.
    """
    mise = _which("mise")
    destination = generated_project.destination
    mise_env = generated_project.mise_env
    install_root = Path(mise_env["MISE_DATA_DIR"])

    selected = Path(
        _run_ok((mise, "which", "python"), cwd=destination, env=mise_env).stdout.strip()
    )
    assert selected.is_relative_to(install_root), selected

    venv_base_prefix = _run_ok(
        (destination / ".venv" / "bin" / "python", "-c", "import sys; print(sys.base_prefix)"),
        cwd=destination,
    ).stdout.strip()
    selected_base_prefix = _run_ok(
        (mise, "exec", "--", "python", "-c", "import sys; print(sys.base_prefix)"),
        cwd=destination,
        env=mise_env,
    ).stdout.strip()

    assert venv_base_prefix == selected_base_prefix, (
        f".venv was built by {venv_base_prefix}, the project's toolchain selects "
        f"{selected_base_prefix}"
    )
    assert Path(venv_base_prefix).is_relative_to(install_root), venv_base_prefix
    assert not Path(venv_base_prefix).is_relative_to(REPO_ROOT)

    # The documented check: the interpreter the environment uses is the one mise
    # selected, resolved through the `bin/python` symlink.
    venv_python = Path(os.path.realpath(destination / ".venv" / "bin" / "python"))
    assert venv_python == Path(os.path.realpath(selected)), (venv_python, selected)


